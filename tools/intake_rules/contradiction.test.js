'use strict';
// node --test tools/intake_rules/  (без браузера, без сети). Только синтетика.
const test = require('node:test');
const assert = require('node:assert');
const { isContradiction, findContradictions, MAX_TEXT_CHARS, TOO_LONG_TEXT } = require('./contradiction.js');

// [id, a, b]. K* — ложные из HOLD b16 v3; H16/C5/C3 — по поручению.
const MUST_NOT_CONTRADICT = [
  ['K01', 'Себестоимость датчика 3 тысячи рублей', 'Розничная цена датчика 9 тысяч рублей'],
  ['K02', 'Зарплаты в 2026 году 5 млн рублей', 'Аренда в 2026 году 1 млн рублей'],
  ['K03', 'В первой клинике 200 пациентов', 'Во второй клинике 350 пациентов'],
  ['K08', 'Первый пилот в одной лаборатории', 'Второй этап в нескольких лабораториях'],
  ['K12', 'Вес устройства 300 г', 'Вес упаковки 450 г'],
  ['H16', 'Средний чек 15 тысяч', 'Подписка 180 тысяч в год'],
  ['C5', 'Не ставит диагноз, не является медизделием', 'Решение о лечении принимает врач'],
  ['C3', 'Штатный инженер', 'Внешний консультант'],
  // свои отрицательные пары (≥10)
  ['N01', 'Выручка в 2025 году 10 млн рублей', 'Выручка в 2026 году 25 млн рублей'],
  ['N02', 'Маржинальность 40 %', 'Затраты на маркетинг 2 млн рублей'],
  ['N03', 'В первом квартале 5 клиентов', 'Во втором квартале 9 клиентов'],
  ['N04', 'Цена подписки 5 тысяч в месяц', 'Себестоимость подписки 1 тысяча в месяц'],
  ['N05', 'Команда: 4 сотрудника в офисе', 'Прототип весит 2 кг'],
  ['N06', 'В пилоте участвует одна клиника', 'На втором этапе подключатся несколько клиник'],
  ['N07', 'Вес датчика 50 г', 'Вес прибора 2 кг'],
  ['N08', 'Аренда офиса 100 тысяч рублей', 'Зарплата инженера 200 тысяч рублей'],
  ['N09', 'Продукт не является медицинским изделием', 'Мы планируем регистрацию в следующем году'],
  ['N10', 'В 2025 году 3 лаборатории', 'В 2026 году 7 лабораторий'],
  ['N11', 'Размер рынка 5 млрд рублей', 'Наша цена 10 тысяч рублей'],
  ['N12', 'Цена датчика 9 тысяч рублей', 'Цена датчика 9000 рублей'],
  ['N13', 'Стоимость датчика 3 тысячи рублей', 'Себестоимость датчика 4 тысячи рублей'],
];
// S3-SYN-07 и T6 — из поручения. C1–C8 из набора ChatGPT в треде НЕ приведены: ниже P01–P08 — СВОИ
// синтетические положительные пары-заглушки. Настоящие C1–C8 добавить в этот массив тем же форматом.
const MUST_CONTRADICT = [
  ['S3-SYN-07', 'У нас 12 клиник-клиентов', 'Ещё 10 клиник: письма о намерениях'],
  ['T6', 'Продукт работает в одной клинике', 'Продукт работает в нескольких клиниках'],
  ['P01', 'Розничная цена датчика 9 тысяч рублей', 'Розничная цена датчика 12 тысяч рублей'],
  ['P02', 'Вес устройства 300 г', 'Вес устройства 450 г'],
  ['P03', 'В первой клинике 200 пациентов', 'В первой клинике 350 пациентов'],
  ['P04', 'Продукт является медицинским изделием', 'Продукт не является медицинским изделием'],
  ['P05', 'Аренда офиса в 2026 году 1 млн рублей', 'Аренда офиса в 2026 году 3 млн рублей'],
  ['P06', 'Пилот проходит в одной лаборатории', 'Пилот проходит в нескольких лабораториях'],
  ['P07', 'Выручка 10 млн рублей', 'Выручка 25 млн рублей'],
  ['P08', 'Данные хранятся в России', 'Данные не хранятся в России'],
];

for (const [id, a, b] of MUST_NOT_CONTRADICT) {
  test('не противоречие: ' + id, () => assert.notStrictEqual(isContradiction(a, b).verdict, 'contradiction', isContradiction(a, b).reason));
}
for (const [id, a, b] of MUST_CONTRADICT) {
  test('противоречие: ' + id, () => assert.strictEqual(isContradiction(a, b).verdict, 'contradiction'));
}

test('clarify: этап назван только с одной стороны', () => {
  const r = isContradiction('В первой клинике 200 пациентов', 'Пациентов 350');
  assert.strictEqual(r.verdict, 'clarify');
});
test('clarify: показатель не назван', () => {
  assert.strictEqual(isContradiction('Датчик: 5 тысяч', 'Датчик: 9 тысяч').verdict, 'clarify');
});
test('clarify: «стоимость» двусмысленна', () => {
  assert.strictEqual(isContradiction('Стоимость датчика 3 тысячи', 'Цена датчика 9 тысяч').verdict, 'clarify');
});
test('clarify: «один/несколько» при одном названном этапе', () => {
  assert.strictEqual(isContradiction('Пилот в одной клинике', 'В нескольких клиниках').verdict, 'clarify');
});
test('вердикт всегда с причиной', () => {
  for (const [, a, b] of [...MUST_NOT_CONTRADICT, ...MUST_CONTRADICT]) {
    const r = isContradiction(a, b);
    assert.ok(['contradiction', 'clarify', 'none'].includes(r.verdict)); assert.ok(r.reason && r.reason.length > 3);
  }
});
test('не строки и длинный фрагмент не падают', () => {
  assert.strictEqual(isContradiction(null, 'x').verdict, 'none');
  assert.strictEqual(isContradiction('а'.repeat(5000), 'б').verdict, 'clarify');
});
test('findContradictions: длиннее предела -> понятная строка без расчёта', () => {
  const r = findContradictions('Текст. '.repeat(MAX_TEXT_CHARS));
  assert.strictEqual(r.error, TOO_LONG_TEXT); assert.deepStrictEqual(r.pairs, []);
});
test('findContradictions: находит пару в тексте и не трогает совместимые', () => {
  const r = findContradictions('Цена датчика 9 тысяч рублей. Себестоимость датчика 3 тысячи рублей. Цена датчика 12 тысяч рублей.');
  assert.strictEqual(r.pairs.filter(p => p.verdict === 'contradiction').length, 1);
});
test('20000 знаков укладываются в 5 секунд', () => {
  const unit = 'Вес устройства 300 г. Цена датчика 9 тысяч рублей. В первой клинике 200 пациентов. Аренда офиса 100 тысяч рублей. ';
  const text = unit.repeat(Math.floor(MAX_TEXT_CHARS / unit.length));
  const t0 = Date.now(); const r = findContradictions(text); const ms = Date.now() - t0;
  assert.strictEqual(r.error, null); assert.ok(ms < 5000, 'время ' + ms + ' мс');
});
