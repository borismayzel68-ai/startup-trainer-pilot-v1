# Слово-признак явного «данных нет» в ответе.
_NO_DATA_RE = re.compile(
    r"^\s*(нет данных|данных нет|не зна(ю|ем)|не измеряли|не проверяли|пока нет)\b",
    re.IGNORECASE,
)


def normalize_status(value: Any) -> str:
    """Любой статус вне четырёх -> 'weak' (консервативно). 'unverified' -> 'weak'."""
    s = str(value or "").strip().lower()
    return s if s in ALLOWED_STATUS else "weak"


def empty_entry() -> dict:
    return {"value": None, "evidence_span": None, "status": "missing", "source": None}


def is_no_data(text: str) -> bool:
    return bool(_NO_DATA_RE.match(text or ""))


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "")).strip().lower()


def span_in(span: str | None, *texts: str) -> bool:
    """Цитата обязана быть дословной (с точностью до пробелов/регистра)."""
    if not span or len(span.strip()) < 3:
        return False
    s = _norm(span)
    return any(s in _norm(t) for t in texts if t)


def first_sentence(text: str, limit: int = 220) -> str:
    text = (text or "").strip()
    m = re.match(r"(.+?[.!?])(\s|$)", text, re.S)
    sent = m.group(1) if m else text
    return sent[:limit].strip()


def numbers(text: str) -> set[str]:
    return set(re.findall(r"\d+(?:[.,]\d+)?", text or ""))


def compute_gaps(profile: dict, asked_ids: set[str] | None = None) -> list[dict]:
    """
    Приоритезированные пробелы: missing > weak > hypothesis, внутри — по
    весу измерения (из scoring.py), затем по порядку SLOTS. fact — не пробел.
    asked_ids помечаются, но не удаляются (решение о переоткрытии — в plan).
    """
    from trainer.scoring import DIMENSION_WEIGHTS

    status_weight = {"missing": 3, "weak": 2, "hypothesis": 1}
    asked_ids = asked_ids or set()
    gaps = []
    for order, slot_id in enumerate(SLOT_IDS):
        entry = profile.get(slot_id) or empty_entry()
        status = normalize_status(entry.get("status"))
        if status == "fact":
            continue
        dim = SLOTS[slot_id]["dimension"]
        weight = DIMENSION_WEIGHTS[dim]
        gaps.append({
            "field_id": slot_id,
            "status": status,
            "dimension": dim,
            "priority": round(status_weight[status] * weight, 4),
            "asked": slot_id in asked_ids,
            "_order": order,
        })
    gaps.sort(key=lambda g: (-g["priority"], g["_order"]))
    for g in gaps:
        g.pop("_order")
    return gaps
