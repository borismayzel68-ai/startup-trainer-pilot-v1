def detect_topic(question: str, explicit: str | None = None) -> str | None:
    """Тема по ключевым словам вопроса (больше совпадений — выше). Явно заданная тема важнее."""
    if explicit in TOPICS:
        return explicit
    q = question.lower()
    best, score = None, 0
    for key, t in TOPICS.items():
        s = sum(1 for k in t["keys"] if k in q)
        if s > score:
            best, score = key, s
    return best
